type ProductTemplate = Omit<Product, 'id' | 'slug' | 'imageUrl'> & {
  variantOptions?: { single?: boolean; seven?: boolean };
};

function toProduct(template: ProductTemplate, index: number): Product {
  const id = `prod-${String(index + 1).padStart(3, '0')}`;
  const slug = slugify(template.name);
  return {
    ...template,
    id,
    slug,
    variants: makeVariants(
      index + 1,
      [9.5, 12.5, 15, 18, 20],
      template.variantOptions,
    ),
    imageUrl: svgPlaceholder(template.facePaper, template.name),
  };
}

