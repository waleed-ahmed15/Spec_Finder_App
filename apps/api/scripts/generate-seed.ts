const facePaperColors: Record<string, string> = {
  pink: '#D6336C',
  green: '#2F9E68',
  ivory: '#B8A88A',
  grey: '#4C5A6B',
  none: '#DFE1DE',
};

function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function svgPlaceholder(facePaper: string, label: string): string {
  const color = facePaperColors[facePaper] ?? facePaperColors.none;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="480" height="320" viewBox="0 0 480 320"><rect width="480" height="320" fill="#FBFBFA"/><rect x="40" y="40" width="400" height="240" rx="4" fill="${color}" fill-opacity="0.15" stroke="${color}" stroke-width="2"/><text x="240" y="170" text-anchor="middle" font-family="monospace" font-size="14" fill="#16191C">${label}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

function materialNumber(index: number): string {
  return String(7600000 + index).padStart(8, '0');
}

function makeVariants(
  productIndex: number,
  thicknesses: number[],
  options?: { single?: boolean; seven?: boolean },
): Product['variants'] {
  if (options?.single) {
    return [
      {
        materialNumber: materialNumber(productIndex * 10),
        widthMm: 1200,
        lengthMm: 2400,
        thicknessMm: thicknesses[0] ?? 12.5,
        weightKg: 28.8,
        weightPerSqmKg: 10.0,
        piecesPerPallet: 52,
        coverageSqm: 2.88,
      },
    ];
  }

  const count = options?.seven ? 7 : Math.min(thicknesses.length, 4);
  const selected = options?.seven
    ? [9.5, 12.5, 15, 18, 20, 25, 30]
    : thicknesses.slice(0, count);

  return selected.map((thickness, i) => ({
    materialNumber: materialNumber(productIndex * 10 + i),
    widthMm: 1200,
    lengthMm: i % 2 === 0 ? 2400 : 3000,
    thicknessMm: thickness,
    weightKg: Number((thickness * 1.9).toFixed(1)),
    weightPerSqmKg: Number((thickness * 0.8).toFixed(1)),
    piecesPerPallet: 40 + i * 4,
    coverageSqm: Number(
      ((1200 * (i % 2 === 0 ? 2400 : 3000)) / 1_000_000).toFixed(2),
    ),
  }));
}

